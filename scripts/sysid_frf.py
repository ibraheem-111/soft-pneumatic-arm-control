"""Frequency-domain system identification (D3) of the open-loop plant, make_sim().

Identification uses only hardware-available signals: the pressure commands, the
20 pouch-pressure sensors, and tip position with added measurement noise. The
privileged `p_actual` and the 50-state linearization from `plant_model.py` are
used only to check results (the "answer key").

Step 0 (setup): two differential input channels around a bias on every pouch,
    x channel: S1 = bias + ux/2, S3 = bias - ux/2   (all five levels)
    y channel: S2 = bias + uy/2, S4 = bias - uy/2
and the measured differential pressure of each channel, e.g.
    px_meas = mean over levels of (S1 sensor - S3 sensor).
Step 1 (two-stage split): stage A = command -> measured pressure (the lag),
stage B = measured pressure -> tip (the mechanics), end to end = command -> tip.
Step 2 (excitation): a random-phase odd multisine with detection lines (one odd
line in every group of four left out at random), phases chosen for a low crest
factor, scaled to a 2 psi peak (and 1 psi for the amplitude check). v1: f0 =
0.02 Hz, every odd line to 2.98 Hz. v2 (default): f0 = 0.01 Hz, odd lines thinned
to a quasi-log grid to 2.99 Hz, so more lines sit at the slow dynamics. Both
channels are excited at once in a Hadamard pair: "+" applies (m, m), "-" (m, -m).
Step 3 (experiments): 6 periods per experiment, the first discarded as transient;
raw data cached in .cache/ (regenerated by `run`).
Step 4 (frequency response): per kept period p and excited line k,
G_p(k) = Y_p(k) U_p(k)^-1 from the DFTs of the two experiments; mean over periods,
standard error from the spread; compared with the answer key.
Lag: tau identified from the stage A response (and, as a check, from the tip alone)
without using the simulator's value.

Usage:
    uv run python scripts/sysid_frf.py setup                    # steps 0-1
    uv run python scripts/sysid_frf.py design [--excitation v1]  # step 2
    uv run python scripts/sysid_frf.py run [--excitation v1]     # step 3 (about 4 min for v2)
    uv run python scripts/sysid_frf.py frf [--excitation v1]     # step 4
    uv run python scripts/sysid_frf.py lag [--excitation v1]     # lag from data
"""

