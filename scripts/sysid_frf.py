    ax[0, 0].set(ylabel="psi", title="Stage A: command → differential pressure")
    ax[0, 1].plot(t, 1000 * r["tip_meas"][:, 0], color="0.7", lw=0.6, label="measured tip x (+0.1 mm noise)")
    ax[0, 1].plot(t, 1000 * tip, lw=1.5, label="true tip x")
