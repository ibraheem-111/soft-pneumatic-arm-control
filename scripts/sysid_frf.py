def split_key(Gk: np.ndarray) -> dict:
    """Answer-key A (command->pressure), E (command->tip), B (pressure->tip)."""
    GA, GE = Gk[:, 2:4, :], Gk[:, 0:2, :]
    return {"A": GA, "E": GE, "B": GE @ np.linalg.inv(GA)}


