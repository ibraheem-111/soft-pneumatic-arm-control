"""Frequency-domain system identification (D3) of the open-loop plant, make_sim().

Identification uses only hardware-available signals: the pressure commands, the
20 pouch-pressure sensors, and tip position with added measurement noise. The
privileged `p_actual` and the 50-state linearization from `plant_model.py` are
used only to check results (the "answer key").

Step 0 (setup): two differential input channels around a bias on every pouch,
    x channel: S1 = bias + ux/2, S3 = bias - ux/2   (all five levels)
    y channel: S2 = bias + uy/2, S4 = bias - uy/2
and the measured differential pressure of each channel, e.g.
    px_meas = mean over levels of (S1 sensor - S3 sensor).
Step 1 (two-stage split): stage A = command -> measured pressure (the lag),
stage B = measured pressure -> tip (the mechanics), end to end = command -> tip.
Step 2 (excitation): a random-phase odd multisine, f0 = 0.02 Hz (50 s period),
odd harmonics up to 2.98 Hz, one odd line in every group of four left out at
random as a detection line; phases chosen for a low crest factor; scaled to a
peak of 2 psi (and 1 psi for the amplitude check). Both channels are excited at
once in a Hadamard pair: experiment "+" applies (m, m), experiment "-" (m, -m).
Step 3 (experiments): 6 periods per experiment, the first periods discarded as
transient; raw data cached in .cache/ (regenerated by `run`).

Usage:
    uv run python scripts/sysid_frf.py setup     # steps 0-1: step tests, figure, checks
    uv run python scripts/sysid_frf.py design    # step 2: excitation signal, figure
    uv run python scripts/sysid_frf.py run       # step 3: run experiments, steady-state and spectrum checks
"""

import argparse
import sys
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import mujoco
import numpy as np
from scipy.signal import cont2discrete

from soft_robotic_arm import make_sim

sys.path.insert(0, str(Path(__file__).resolve().parent))
from plant_model import equilibrium, linearize  # noqa: E402

CONTROL_HZ = 100.0
BIAS_PSI = 4.5
TIP_NOISE_M = 1e-4          # assumed motion-capture noise, 0.1 mm (not the lab's measured figure)
SIM_SEED = 11               # identification seeds; validation must use different ones
NOISE_SEED = 11
FIG_DIR = Path(__file__).resolve().parent.parent / "docs" / "figures"
CACHE = Path(__file__).resolve().parent.parent / ".cache" / "sysid_frf_runs.npz"

F0_HZ = 0.02                # frequency resolution; period 50 s
N_PERIOD = int(round(CONTROL_HZ / F0_HZ))
K_MAX = 149                 # highest odd harmonic, 2.98 Hz
N_PERIODS = 6
N_TRANSIENT = 2             # periods discarded before averaging
PHASE_SEED = 21
AMPLITUDES = (2.0, 1.0)     # peak psi per channel

# Rows of the (4, 5) command: S1..S4. Channel -> (positive segment, negative segment).
CHANNELS = {"x": (0, 2), "y": (1, 3)}


def channel_matrix() -> np.ndarray:
    """T (20 x 2): pouch-command deviations (flattened S1P1..S4P5) per unit (ux, uy)."""
    T = np.zeros((4, 5, 2))
    for j, (pos, neg) in enumerate(CHANNELS.values()):
        T[pos, :, j] = 0.5
        T[neg, :, j] = -0.5
    return T.reshape(20, 2)


def sensor_matrix() -> np.ndarray:
    """S (2 x 20): measured channel pressure = mean over levels of (pos - neg) sensors."""
    S = np.zeros((2, 4, 5))
    for j, (pos, neg) in enumerate(CHANNELS.values()):
        S[j, pos, :] = 1 / 5
        S[j, neg, :] = -1 / 5
    return S.reshape(2, 20)


class ChannelPlant:
    """make_sim() driven through the two differential channels about a uniform bias."""

    def __init__(self, sim_seed: int = SIM_SEED, noise_seed: int = NOISE_SEED,
                 bias: float = BIAS_PSI, tip_noise: float = TIP_NOISE_M):
        self.sim = make_sim(control_hz=CONTROL_HZ, seed=sim_seed)
        self.bias = bias
        self.tip_noise = tip_noise
        self.rng = np.random.default_rng(noise_seed)
        self.T = channel_matrix().reshape(4, 5, 2)
        self.S = sensor_matrix()
        self.q0 = equilibrium(self.sim, bias)          # settle 60 s at the bias
        self.home = self.sim.data.sensordata[0:2].copy()

    def step(self, ux: float, uy: float) -> dict:
        command = np.clip(self.bias + self.T @ np.array([ux, uy]), 0.0, 9.0)
        obs = self.sim.step(command)
        tip = obs["tip_pos"][:2] - self.home
        return {
            # identification signals (available on hardware)
            "u": np.array([ux, uy]),
            "p_meas": self.S @ obs["pouch_pressures"].ravel(),
            "tip_meas": tip + self.rng.normal(0.0, self.tip_noise, 2),
            # privileged, for checking only
            "p_true": self.S @ self.sim.p_actual.ravel(),
            "tip_true": tip,
        }

    def run(self, u: np.ndarray) -> dict[str, np.ndarray]:
        """Apply a (N, 2) channel sequence; return stacked signals."""
        records = [self.step(*uk) for uk in u]
        return {k: np.array([r[k] for r in records]) for k in records[0]}


def answer_key(plant: ChannelPlant):
    """Channel-level linear model from plant_model.linearize: (A, B2, C) with
    outputs [tip x, tip y, px_meas, py_meas] and inputs (ux, uy), continuous time."""
    A, B, C = linearize(plant.sim, plant.q0, plant.bias)
    B2 = B @ channel_matrix()
    C4 = np.vstack([C[0:2], plant.S @ C[3:]])
    return A, B2, C4


def simulate_linear(A, B, C, u: np.ndarray) -> np.ndarray:
    """ZOH-discretized response from zero state; same timing as ChannelPlant.run."""
    Ad, Bd, *_ = cont2discrete((A, B, C, np.zeros((C.shape[0], B.shape[1]))), 1 / CONTROL_HZ)
    x = np.zeros(A.shape[0])
    out = []
    for uk in u:
        x = Ad @ x + Bd @ uk
        out.append(C @ x)
    return np.array(out)


def t63(t: np.ndarray, y: np.ndarray) -> float:
    """Time to reach 63.2 % of the final value (final = mean of the last second)."""
    final = y[-int(CONTROL_HZ):].mean()
    return float(t[np.argmax(np.abs(y) >= 0.632 * abs(final))])


def setup_checks() -> None:
    """Steps 0-1: +/-2 psi steps on each channel, checked against the answer key."""
    hold_s, amp = 15.0, 2.0
    n = int(hold_s * CONTROL_HZ)
    t = np.arange(1, n + 1) / CONTROL_HZ
    plant_x = ChannelPlant()
    A, B2, C4 = answer_key(plant_x)
    dc = C4 @ np.linalg.solve(-A, B2)          # 4 x 2 static gains of the answer key

    runs = {}
    for name, u in {"+x": (amp, 0.0), "-x": (-amp, 0.0), "+y": (0.0, amp)}.items():
        plant = plant_x if name == "+x" else ChannelPlant()
        runs[name] = plant.run(np.tile(u, (n, 1)))
    key = simulate_linear(A, B2, C4, np.tile((amp, 0.0), (n, 1)))

    r = runs["+x"]
    last = slice(-int(CONTROL_HZ), None)
    print("Step 0 - channels and outputs (make_sim, bias 4.5 psi, +2 psi steps, 15 s)")
    print(f"  settled tip (home): x {1000 * plant_x.home[0]:+.3f} mm, y {1000 * plant_x.home[1]:+.3f} mm")
    for name, (j, ax) in {"+x": (0, 0), "+y": (1, 1)}.items():
        tip = runs[name]["tip_true"][last].mean(0) * 1000 / amp
        print(f"  {name} step: tip gain x {tip[0]:+.4f}, y {tip[1]:+.4f} mm/psi  |  answer key "
              f"x {1000 * dc[0, j]:+.4f}, y {1000 * dc[1, j]:+.4f} mm/psi")
    sym = runs["-x"]["tip_true"][last, 0].mean() / runs["+x"]["tip_true"][last, 0].mean()
    print(f"  linearity: tip x for -2 psi / +2 psi = {sym:+.4f}  (exactly -1 if linear)")
    noise = (r["tip_meas"] - r["tip_true"]).std(0) * 1000
    print(f"  added tip noise: std {noise.round(4)} mm (set {1000 * TIP_NOISE_M} mm)")

    print("Step 1 - two-stage split (+x step)")
    pm, pt, tip = r["p_meas"][:, 0], r["p_true"][:, 0], r["tip_true"][:, 0]
    print(f"  stage A, command -> pressure: t63 true {t63(t, pt):.2f} s, measured {t63(t, pm):.2f} s "
          f"(lag tau = {plant_x.sim.cfg.tau_pneumatic} s)")
    print(f"  final pressure: true {pt[last].mean():.4f} psi, measured {pm[last].mean():.4f} psi "
          f"(command {amp} psi)")
    err = pm - pt
    print(f"  sensor error (measured - true): final {err[last].mean():+.4f} psi, "
          f"max |err| {np.abs(err).max():.4f} psi, = {100 * err[last].mean() / pt[last].mean():+.2f} % of signal")
    print(f"  answer key final measured pressure {key[last, 2].mean():.4f} psi")
    g_true = tip[last].mean() / pt[last].mean() * 1000
    g_meas = tip[last].mean() / pm[last].mean() * 1000
    print(f"  stage B static gain tip/pressure: with true pressure {g_true:.4f} mm/psi, "
          f"with measured pressure {g_meas:.4f} mm/psi")
    print(f"  end to end: tip t63 {t63(t, tip):.2f} s vs pressure t63 {t63(t, pt):.2f} s")
    rms = np.sqrt(np.mean((tip - key[:, 0]) ** 2)) * 1000
    print(f"  answer key vs nonlinear sim, tip x over the step: RMS difference {rms:.4f} mm "
          f"(tip moves {1000 * abs(tip[last].mean()):.3f} mm)")

    fig, ax = plt.subplots(2, 2, figsize=(11, 7), sharex=True)
    ax[0, 0].plot(t, np.full_like(t, amp), "k--", lw=1, label="command ux")
    ax[0, 0].plot(t, pm, lw=1, label="measured px (sensors)")
    ax[0, 0].plot(t, pt, lw=1.5, label="true px (p_actual, check only)")
    ax[0, 0].plot(t, key[:, 2], ":", lw=1.5, label="answer key, measured px")
    ax[0, 0].set(ylabel="psi", title="Stage A: command → differential pressure")
    ax[0, 1].plot(t, 1000 * r["tip_meas"][:, 0], color="0.7", lw=0.6, label="measured tip x (+0.1 mm noise)")
    ax[0, 1].plot(t, 1000 * tip, lw=1.5, label="true tip x")
    ax[0, 1].plot(t, 1000 * key[:, 0], ":", lw=1.5, label="answer key")
    ax[0, 1].set(ylabel="mm", title="End to end: command → tip x")
    ax[1, 0].plot(t, err, lw=1)
    ax[1, 0].set(xlabel="time after step [s]", ylabel="psi",
                 title="Sensor error: measured − true pressure (curvature coupling)")
    ax[1, 1].plot(t, 1000 * runs["+x"]["tip_true"][:, 1], lw=1.2, label="tip y, +x step")
    ax[1, 1].plot(t, 1000 * runs["+y"]["tip_true"][:, 1], lw=1.2, label="tip y, +y step")
    ax[1, 1].plot(t, -1000 * runs["-x"]["tip_true"][:, 0], "--", lw=1.2, label="−(tip x), −x step")
    ax[1, 1].plot(t, 1000 * tip, ":", lw=1.2, label="tip x, +x step")
    ax[1, 1].set(xlabel="time after step [s]", ylabel="mm", title="Decoupling and symmetry")
    for a in ax.flat:
        a.grid(True, alpha=0.3)
        if a.get_legend_handles_labels()[0]:
            a.legend(fontsize=8)
    fig.suptitle("make_sim, bias 4.5 psi on every pouch, ±2 psi steps on the differential channels")
    fig.tight_layout()
    out = FIG_DIR / "sysid_setup_steps.png"
    fig.savefig(out, dpi=130)
    print(f"  figure: {out.relative_to(FIG_DIR.parent.parent)}")


def design_multisine(peak: float = AMPLITUDES[0], seed: int = PHASE_SEED, tries: int = 500) -> dict:
    """Random-phase odd multisine over one period, flat amplitude on the excited lines.

    Odd harmonics 1..K_MAX are split into groups of four; one line per group is left
    out at random and becomes an odd detection line. Of `tries` random phase sets the
    one with the lowest crest factor (peak / rms) is kept."""
    rng = np.random.default_rng(seed)
    odd = np.arange(1, K_MAX + 1, 2)
    excited, detect_odd = [], []
    for g in range(0, odd.size, 4):
        group = odd[g:g + 4]
        drop = rng.integers(group.size) if group.size == 4 else -1
        for i, k in enumerate(group):
            (detect_odd if i == drop else excited).append(k)
    excited = np.array(excited)
    best_cf, best = np.inf, None
    for _ in range(tries):
        spectrum = np.zeros(N_PERIOD // 2 + 1, complex)
        spectrum[excited] = np.exp(1j * rng.uniform(0, 2 * np.pi, excited.size))
        x = np.fft.irfft(spectrum, N_PERIOD)
        cf = np.abs(x).max() / x.std()
        if cf < best_cf:
            best_cf, best = cf, x
    return {"signal": best * peak / np.abs(best).max(), "excited": excited,
            "detect_odd": np.array(detect_odd), "crest": best_cf, "peak": peak}


def design_report() -> None:
    """Step 2: describe and plot the excitation."""
    d = design_multisine()
    m, exc, det = d["signal"], d["excited"], d["detect_odd"]
    per_line = 2 * np.abs(np.fft.rfft(m)[exc]).mean() / N_PERIOD
    command = BIAS_PSI + channel_matrix() @ np.vstack([m, m])   # experiment "+"
    print("Step 2 - excitation design")
    print(f"  period {N_PERIOD / CONTROL_HZ:.0f} s ({N_PERIOD} samples), resolution {F0_HZ} Hz")
    print(f"  excited lines: {exc.size} odd harmonics, {exc[0] * F0_HZ:.2f}-{exc[-1] * F0_HZ:.2f} Hz")
    print(f"  detection lines: {det.size} odd (left out) + all even harmonics")
    print(f"  crest factor {d['crest']:.2f} (a single sine is 1.41); rms {m.std():.3f} psi at peak {d['peak']} psi")
    print(f"  amplitude per excited line {per_line:.4f} psi")
    print(f"  pouch commands over a period: {command.min():.2f}-{command.max():.2f} psi (limit 0-9)")
    print(f"  lag corner {1 / (2 * np.pi * 0.6):.2f} Hz; slow real poles "
          f"{1.25 / (2 * np.pi):.2f}-{1.81 / (2 * np.pi):.2f} Hz; mechanical pair 1.14 Hz")

    t = np.arange(N_PERIOD) / CONTROL_HZ
    fig, ax = plt.subplots(1, 2, figsize=(12, 4))
    ax[0].plot(t, m, lw=0.8)
    ax[0].axhline(d["peak"], color="k", ls=":", lw=1)
    ax[0].axhline(-d["peak"], color="k", ls=":", lw=1)
    ax[0].set(xlabel="time [s]", ylabel="channel command deviation [psi]",
              title=f"One period of the multisine (crest factor {d['crest']:.2f})")
    amp = 2 * np.abs(np.fft.rfft(m)) / N_PERIOD
    f = np.arange(amp.size) * F0_HZ
    ax[1].vlines(f[exc], 0, amp[exc], color="C0", lw=1.5, label=f"excited odd lines ({exc.size})")
    ax[1].plot(f[det], np.full(det.size, amp[exc].max() * 0.15), "x", color="C3",
               label=f"odd detection lines ({det.size})")
    ax[1].axvline(1 / (2 * np.pi * 0.6), color="k", ls="--", lw=1, label="lag corner 0.27 Hz")
    ax[1].axvline(1.142, color="k", ls=":", lw=1, label="mechanical pair 1.14 Hz")
    ax[1].axvspan(1.25 / (2 * np.pi), 1.81 / (2 * np.pi), color="0.85", label="slow real poles")
    ax[1].set(xscale="log", xlim=(0.015, 4), xlabel="frequency [Hz]", ylabel="amplitude [psi]",
              title="Amplitude spectrum (even harmonics are all detection lines)")
    for a in ax:
        a.grid(True, alpha=0.3)
    ax[1].legend(fontsize=8, loc="lower left")
    fig.tight_layout()
    out = FIG_DIR / "sysid_excitation.png"
    fig.savefig(out, dpi=130)
    print(f"  figure: {out.relative_to(FIG_DIR.parent.parent)}")


def run_experiments() -> dict:
    """Step 3: Hadamard pair of experiments at each amplitude; cache raw signals."""
    base = design_multisine()
    data = {"excited": base["excited"], "detect_odd": base["detect_odd"]}
    i = 0
    for peak in AMPLITUDES:
        m = base["signal"] * peak / base["peak"]
        for sign, label in ((1.0, "+"), (-1.0, "-")):
            u = np.tile(np.column_stack([m, sign * m]), (N_PERIODS, 1))
            plant = ChannelPlant(sim_seed=SIM_SEED + i, noise_seed=NOISE_SEED + i)
            for k, v in plant.run(u).items():
                data[f"{peak:g}{label}/{k}"] = v
            i += 1
    CACHE.parent.mkdir(exist_ok=True)
    np.savez_compressed(CACHE, **data)
    return data


def periods_dft(x: np.ndarray) -> np.ndarray:
    """(N_PERIODS * N_PERIOD, c) -> (N_PERIODS, N_PERIOD // 2 + 1, c), DFT of each period."""
    return np.fft.rfft(x.reshape(N_PERIODS, N_PERIOD, -1), axis=1)


def run_report() -> None:
    """Step 3: run, then check steady state, SNR and the raw output spectra."""
    data = run_experiments()
    exc, det_odd = data["excited"], data["detect_odd"]
    even = np.arange(2, K_MAX + 1, 2)
    keep = slice(N_TRANSIENT, None)
    print("Step 3 - experiments")
    print(f"  {len(AMPLITUDES) * 2} experiments x {N_PERIODS} periods = "
          f"{len(AMPLITUDES) * 2 * N_PERIODS * N_PERIOD / CONTROL_HZ:.0f} s simulated; cached in .cache/{CACHE.name}")
    print("  steady state: relative change of each period's spectrum vs the last period (excited lines)")
    changes = {}
    for exp in ("2+", "2-", "1+", "1-"):
        for sig, name in (("p_meas", "px"), ("tip_meas", "tip x"), ("tip_true", "tip x true")):
            Y = periods_dft(data[f"{exp}/{sig}"])[:, exc, 0]
            changes[(exp, name)] = np.linalg.norm(Y - Y[-1], axis=1) / np.linalg.norm(Y[-1])
            if exp == "2+":
                print(f"    {exp} {name:<11}" + "  ".join(
                    f"P{p + 1} {c:.1e}" for p, c in enumerate(changes[(exp, name)][:-1])))
    print(f"  averaging periods {N_TRANSIENT + 1}-{N_PERIODS} ({N_PERIODS - N_TRANSIENT} periods)")
    print("  raw output spectra over kept periods (medians over lines, relative to the excited lines):")
    spectra = {}
    for exp in ("2+", "1+"):
        for sig, name in (("p_meas", "px"), ("tip_meas", "tip x"), ("tip_true", "tip x true")):
            Y = periods_dft(data[f"{exp}/{sig}"])[keep, :, 0]
            Ym = np.abs(Y.mean(0))
            se = np.abs(Y - Y.mean(0)).std(0) * np.sqrt(2) / np.sqrt(Y.shape[0])
            spectra[(exp, name)] = Ym
            e = np.median(Ym[exc])
            snr = 20 * np.log10(np.median(Ym[exc] / np.maximum(se[exc], 1e-30)))
            print(f"    {exp} {name:<11} odd-detection {20 * np.log10(np.median(Ym[det_odd]) / e):+6.1f} dB  "
                  f"even-detection {20 * np.log10(np.median(Ym[even]) / e):+6.1f} dB  "
                  f"median SNR {snr:5.1f} dB")

    exp = "2+"
    t = np.arange(N_PERIODS * N_PERIOD) / CONTROL_HZ
    fig, ax = plt.subplots(3, 1, figsize=(12, 11))
    ax[0].axvspan(0, N_TRANSIENT * N_PERIOD / CONTROL_HZ, color="0.92", label="discarded periods")
    ax[0].plot(t, data[f"{exp}/u"][:, 0], lw=0.5, color="0.55", label="command ux")
    ax[0].plot(t, data[f"{exp}/p_meas"][:, 0], lw=0.6, label="measured px")
    ax0b = ax[0].twinx()
    ax0b.plot(t, 1000 * data[f"{exp}/tip_meas"][:, 0], lw=0.4, color="C3")
    ax0b.set_ylabel("measured tip x [mm]", color="C3")
    ax[0].set(xlabel="time [s]", ylabel="psi", title="Experiment 2+ (peak 2 psi on both channels), 6 periods")
    ax[0].legend(fontsize=8, loc="upper left")
    for (e, name), c in changes.items():
        if name != "tip x true":
            ax[1].semilogy(np.arange(1, N_PERIODS), c[:-1], "o-", ms=4, label=f"{e} {name}")
    ax[1].axvline(N_TRANSIENT + 0.5, color="k", ls=":", lw=1)
    ax[1].set(xlabel="period", ylabel="relative change vs period 6",
              title="Steady state: how much each period's spectrum differs from the last")
    ax[1].legend(fontsize=7, ncol=4)
    f = np.arange(N_PERIOD // 2 + 1) * F0_HZ
    scale = 1000 * 2 / N_PERIOD
    Ym, Yt = spectra[(exp, "tip x")], spectra[(exp, "tip x true")]
    ax[2].loglog(f[exc], scale * Ym[exc], "o", ms=3, label="excited lines")
    ax[2].loglog(f[det_odd], scale * Ym[det_odd], "x", ms=5, label="odd detection lines")
    ax[2].loglog(f[even], scale * Ym[even], ".", ms=3, color="0.5", label="even detection lines")
    ax[2].loglog(f[det_odd], scale * Yt[det_odd], "+", ms=6, color="C3", label="odd detection, noise-free tip (check)")
    ax[2].set(xlim=(0.015, 4), xlabel="frequency [Hz]", ylabel="amplitude [mm]",
              title="Raw spectrum of measured tip x, experiment 2+, mean of the kept periods")
    for a in ax:
        a.grid(True, alpha=0.3, which="both")
    ax[2].legend(fontsize=8)
    fig.tight_layout()
    out = FIG_DIR / "sysid_experiments.png"
    fig.savefig(out, dpi=130)
    print(f"  figure: {out.relative_to(FIG_DIR.parent.parent)}")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("stage", choices=["setup", "design", "run"], help="which part to run")
    args = parser.parse_args()
    {"setup": setup_checks, "design": design_report, "run": run_report}[args.stage]()


if __name__ == "__main__":
    main()
