def fit_complex(model, theta0, w, G, se, names):
    """Weighted nonlinear least squares on a complex FRF: minimise
    sum_k |model(jw_k) - G_k|^2 / se_k^2. Returns estimates, 1-sigma errors, cost."""
    def resid(theta):
        r = (model(1j * w, theta) - G) / se
        return np.concatenate([r.real, r.imag])
    sol = least_squares(resid, theta0, x_scale="jac")
    J = sol.jac
    dof = 2 * w.size - len(theta0)
    s2 = 2 * sol.cost / dof
    cov = np.linalg.pinv(J.T @ J) * s2
    return dict(zip(names, sol.x)), dict(zip(names, np.sqrt(np.diag(cov)))), 2 * sol.cost / dof


def lag_report(version: str) -> None:
    """Identify the pneumatic lag from data, without assuming tau."""
    spec = EXCITATIONS[version]
    data = load_runs(version)
    print(f"Lag identification, excitation {version} (tau is not used anywhere below)")
    rows = []
    for pk in AMPLITUDES:
        e = frf_estimates(data, spec, pk)
        w = 2 * np.pi * e["f"]
        for ch, j in (("x", 0), ("y", 1)):
            G, se = e["A"][:, j, j], e["A_se"][:, j, j]
            # 1) Linear least squares (Levy): G (tau jw + 1) = g  ->  G = g - tau jw G
            M = np.column_stack([np.ones_like(G), -1j * w * G]) / se[:, None]
            rhs = G / se
            Mr = np.vstack([M.real, M.imag])
            g_lin, tau_lin = np.linalg.lstsq(Mr, np.concatenate([rhs.real, rhs.imag]), rcond=None)[0]
            # 2) Nonlinear fit with a free time delay: g exp(-s Td) / (tau s + 1)
            p, sd, chi2 = fit_complex(lambda s, th: th[0] * np.exp(-s * th[2]) / (th[1] * s + 1),
                                      [g_lin, tau_lin, 0.0], w, G, se, ["gain", "tau", "delay"])
            rows.append((pk, ch, tau_lin, p, sd, chi2))
            print(f"  stage A, peak {pk:g} psi, {ch}->{ch}: linear LS tau {tau_lin:.4f} s, gain {g_lin:.4f} | "
                  f"with delay: tau {p['tau']:.4f} +/- {sd['tau']:.4f} s, gain {p['gain']:.4f} +/- {sd['gain']:.4f}, "
                  f"delay {1000 * p['delay']:+.2f} +/- {1000 * sd['delay']:.2f} ms, chi2/dof {chi2:.2f}")

    # End to end only (no pressure sensors): lag x one mechanical mode, several starts
    e = frf_estimates(data, spec, 2.0)
    w = 2 * np.pi * e["f"]
    G, se = e["E"][:, 0, 0], e["E_se"][:, 0, 0]

    def model3(s, th):
        b, tau, wn, zeta = th
        return b / ((tau * s + 1) * (s ** 2 + 2 * zeta * wn * s + wn ** 2))

    dc = np.real(G[0])
    best = None
    for tau0 in (0.05, 0.2, 1.0, 3.0):
        for wn0 in (2.0, 8.0, 20.0):
            for z0 in (0.3, 1.0):
                try:
                    fit = fit_complex(model3, [dc * wn0 ** 2, tau0, wn0, z0], w, G, se,
                                      ["b", "tau", "wn", "zeta"])
                except (ValueError, np.linalg.LinAlgError):
                    continue
                if best is None or fit[2] < best[2]:
                    best = fit
    p, sd, chi2 = best
    print("  end to end only (tip, no pressure sensors), model b / ((tau s + 1)(s^2 + 2 zeta wn s + wn^2)), "
          "best of 24 starts:")
    print(f"    tau {p['tau']:.4f} +/- {sd['tau']:.4f} s, wn {p['wn']:.3f} rad/s ({p['wn'] / (2 * np.pi):.3f} Hz), "
          f"zeta {p['zeta']:.3f}, static gain {1000 * p['b'] / p['wn'] ** 2:.4f} mm/psi, chi2/dof {chi2:.2f}")

    pk, ch, tau_lin, pA, sdA, _ = rows[0]
    eA = frf_estimates(data, spec, 2.0)
    fd = np.geomspace(0.008, 4, 300)
    wd = 2 * np.pi * fd
    fit_A = pA["gain"] * np.exp(-1j * wd * pA["delay"]) / (pA["tau"] * 1j * wd + 1)
    fit_E = model3(1j * wd, [p["b"], p["tau"], p["wn"], p["zeta"]])
    fig, ax = plt.subplots(2, 2, figsize=(12, 7), sharex=True)
    for c, (G, se, fit, lab, sc, unit) in enumerate((
            (eA["A"][:, 0, 0], eA["A_se"][:, 0, 0], fit_A,
             f"fit γ e^(−sT)/(τs+1): τ = {pA['tau']:.3f} s", 1.0, "psi/psi"),
            (eA["E"][:, 0, 0], eA["E_se"][:, 0, 0], fit_E,
             f"fit lag × 2nd order: τ = {p['tau']:.3f} s", 1000.0, "mm/psi"))):
        ax[0, c].errorbar(eA["f"], np.abs(G) * sc, yerr=2 * se * sc, fmt="o", ms=3, label="estimate ± 2 se")
        ax[0, c].loglog(fd, np.abs(fit) * sc, "C1-", lw=1.5, label=lab)
        ax[0, c].set_yscale("log")
        ax[0, c].set(ylabel=f"|G| [{unit}]", title=["Stage A: command → measured pressure",
                                                    "End to end: command → tip (no pressure sensors)"][c])
        ax[1, c].semilogx(eA["f"], np.degrees(np.unwrap(np.angle(G))), "o", ms=3)
        ax[1, c].semilogx(fd, np.degrees(np.unwrap(np.angle(fit))), "C1-", lw=1.5)
        ax[1, c].set(xlabel="frequency [Hz]", ylabel="phase [deg]")
        for r in range(2):
            ax[r, c].grid(True, which="both", alpha=0.3)
        ax[0, c].legend(fontsize=8, loc="lower left")
    fig.suptitle(f"Identifying the pneumatic lag from data (excitation {version}, peak 2 psi, x channel)")
    fig.tight_layout()
    out = FIG_DIR / f"sysid_lag_{version}.png"
    fig.savefig(out, dpi=130)
    print(f"  figure: {out.relative_to(FIG_DIR.parent.parent)}")


