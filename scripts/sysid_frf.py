def fit_vector(model, theta0, w, G, se):
    """Weighted nonlinear least squares on a complex FRF: minimise
    sum_k |model(jw_k) - G_k|^2 / se_k^2. Returns estimates, 1-sigma errors, chi2/dof."""
    def resid(theta):
        r = (model(1j * w, theta) - G) / se
        return np.concatenate([r.real, r.imag])
    sol = least_squares(resid, theta0, x_scale="jac")
    dof = 2 * w.size - len(theta0)
    chi2 = 2 * sol.cost / dof
    cov = np.linalg.pinv(sol.jac.T @ sol.jac) * chi2
    return sol.x, np.sqrt(np.diag(cov)), chi2


def fit_complex(model, theta0, w, G, se, names):
    x, sd, chi2 = fit_vector(model, theta0, w, G, se)
    return dict(zip(names, x)), dict(zip(names, sd)), chi2


def stage_a_fit(e: dict, j: int) -> tuple[dict, dict, float]:
    """Lag from the command -> measured pressure response: g exp(-s T) / (tau s + 1).
    Start: for each trial delay T on a grid (0-1 s), remove it (G e^{jwT}) and solve the
    linear least squares G (tau jw + 1) = g; keep the T with the smallest misfit.
    Neither tau nor T is assumed. `tau_linear` is the linear fit with T = 0."""
    w = 2 * np.pi * e["f"]
    G, se = e["A"][:, j, j], e["A_se"][:, j, j]

    def linear(Gc):
        M = np.column_stack([np.ones_like(Gc), -1j * w * Gc]) / se[:, None]
        rhs = Gc / se
        g, tau = np.linalg.lstsq(np.vstack([M.real, M.imag]), np.concatenate([rhs.real, rhs.imag]), rcond=None)[0]
        return g, tau, np.sum(np.abs(g / (tau * 1j * w + 1) - Gc) ** 2 / se ** 2)

    tau_linear = linear(G)[1]
    T0 = min(np.arange(0.0, 1.0, 1 / CONTROL_HZ), key=lambda T: linear(G * np.exp(1j * w * T))[2])
    g0, tau0, _ = linear(G * np.exp(1j * w * T0))
    p, sd, chi2 = fit_complex(lambda s, th: th[0] * np.exp(-s * th[2]) / (th[1] * s + 1),
                              [g0, tau0, T0], w, G, se, ["gain", "tau", "delay"])
    p["tau_linear"] = tau_linear
    return p, sd, chi2


