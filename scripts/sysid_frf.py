    print(f"  end to end: tip t63 {t63(t, tip):.2f} s vs pressure t63 {t63(t, pt):.2f} s")
    rms = np.sqrt(np.mean((tip - key[:, 0]) ** 2)) * 1000
    print(f"  answer key vs nonlinear sim, tip x over the step: RMS difference {rms:.4f} mm "
          f"(tip moves {1000 * abs(tip[last].mean()):.3f} mm)")

    fig, ax = plt.subplots(2, 2, figsize=(11, 7), sharex=True)
    ax[0, 0].plot(t, np.full_like(t, amp), "k--", lw=1, label="command ux")
