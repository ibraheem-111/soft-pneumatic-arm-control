def frf_estimates(data: dict, spec: dict, peak: float) -> dict:
    """Step 4: nonparametric 2x2 frequency responses on the excited lines.

    For each kept period p and excited line k:  U_p(k) (2 channels x 2 experiments),
    Y_p(k) likewise for each output, and G_p(k) = Y_p(k) U_p(k)^-1. The estimate is the
    mean over periods; its standard error is the spread between periods / sqrt(P)."""
    Pt, exc = spec["transient"], data["excited"]

    def lines(sig: str) -> np.ndarray:   # (periods kept, lines, 2 signals, 2 experiments)
        return np.stack([periods_dft(data[f"{peak:g}{e}/{sig}"], spec)[Pt:, exc, :] for e in "+-"], axis=-1)

    U, Pm, Yt = lines("u"), lines("p_meas"), lines("tip_meas")
    per_period = {"A": Pm @ np.linalg.inv(U), "E": Yt @ np.linalg.inv(U), "B": Yt @ np.linalg.inv(Pm)}
    out = {"f": exc * spec["f0"]}
    for key, G in per_period.items():
        n = G.shape[0]
        mean = G.mean(0)
        out[key] = mean
        out[key + "_se"] = np.sqrt((np.abs(G - mean) ** 2).sum(0) / (n - 1) / n)
    return out


def key_frf(f: np.ndarray, Ad, Bd, C) -> np.ndarray:
    """Answer-key FRF of the sampled plant with the same sample alignment as the runs:
    output k is read after input k is applied, so G(z) = z C (zI - Ad)^-1 Bd."""
    z = np.exp(1j * 2 * np.pi * f / CONTROL_HZ)
    eye = np.eye(Ad.shape[0])
    return np.array([zk * C @ np.linalg.solve(zk * eye - Ad, Bd) for zk in z])   # (F, 4, 2)


