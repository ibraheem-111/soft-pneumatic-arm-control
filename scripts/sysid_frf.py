MODEL_ORDERS = ((0, 2), (1, 3), (2, 4))   # (numerator, denominator) degree of stage B
W_SCALE = 2 * np.pi                        # fit in s' = s / (2 pi rad/s) for conditioning
VAL_SEED = 101                             # validation plant, noise and input seed


def monic(a: np.ndarray) -> np.ndarray:
    return np.concatenate([a, [1.0]])


def rational(s, b: np.ndarray, a: np.ndarray):
    """B(s')/A(s') with ascending coefficients, s' = s / W_SCALE, A monic."""
    sp = s / W_SCALE
    return np.polyval(b[::-1], sp) / np.polyval(monic(a)[::-1], sp)


def fit_rational(w: np.ndarray, G: np.ndarray, se: np.ndarray, nb: int, na: int, iters: int = 30) -> dict:
    """Fit B(s)/A(s) e^{-sT} to an FRF. Sanathanan-Koerner iterations (linear least
    squares on A G - B, reweighted by the previous |A|) give the start; weighted
    nonlinear least squares on the complex residual refines it, with a free delay T."""
    s = 1j * w / W_SCALE
    a = np.zeros(na)
    for _ in range(iters):
        wk = 1 / (se * np.abs(np.polyval(monic(a)[::-1], s)))
        M = np.column_stack([s ** j for j in range(nb + 1)] + [-G * s ** j for j in range(na)]) * wk[:, None]
        rhs = G * s ** na * wk
        x = np.linalg.lstsq(np.vstack([M.real, M.imag]), np.concatenate([rhs.real, rhs.imag]), rcond=None)[0]
        b, a = x[:nb + 1], x[nb + 1:]

    def model(sv, th):
        return rational(sv, th[:nb + 1], th[nb + 1:nb + 1 + na]) * np.exp(-sv * th[-1])

    th, sd, chi2 = fit_vector(model, np.concatenate([b, a, [0.0]]), w, G, se)
    b, a = th[:nb + 1], th[nb + 1:nb + 1 + na]
    return {"b": b, "a": a, "delay": th[-1], "delay_sd": sd[-1], "chi2": chi2,
            "poles": W_SCALE * np.roots(monic(a)[::-1]), "dc": b[0] / a[0], "model": lambda sv: model(sv, th)}


def canonical_ss(b: np.ndarray, a: np.ndarray):
    """Controllable canonical form (course notes, Module 2 section 5.1) of B(s)/A(s),
    converted from the scaled variable s' = s / W_SCALE to s."""
    na = a.size
    ac = a * W_SCALE ** (na - np.arange(na))
    bc = np.zeros(na)
    bc[:b.size] = b * W_SCALE ** (na - np.arange(b.size))
    A = np.zeros((na, na))
    A[:-1, 1:] = np.eye(na - 1)
    A[-1] = -ac
    B = np.zeros((na, 1))
    B[-1, 0] = 1.0
    return A, B, bc[None, :]


def axis_model(stage_a: dict, fit: dict):
    """One axis: lag state p (stage A) feeding the stage B realization.
    x = [p, x_B]:  p' = -p/tau + (g/tau) u,  x_B' = A_B x_B + B_B p,  y = C_B x_B."""
    Ab, Bb, Cb = canonical_ss(fit["b"], fit["a"])
    n = Ab.shape[0] + 1
    A = np.zeros((n, n))
    A[0, 0] = -1 / stage_a["tau"]
    A[1:, 0] = Bb[:, 0]
    A[1:, 1:] = Ab
    B = np.zeros((n, 1))
    B[0, 0] = stage_a["gain"] / stage_a["tau"]
    C = np.zeros((1, n))
    C[0, 1:] = Cb[0]
    return A, B, C


def delay_samples(stage_a: dict) -> int:
    """Input delay in samples. The fitted T includes a -T_s/2 alignment artefact (output
    read after the input has been held one step), which is added back here."""
    return max(0, int(round((stage_a["delay"] + 0.5 / CONTROL_HZ) * CONTROL_HZ)))


def simulate_ss(A, B, C, u: np.ndarray, delay: int = 0) -> np.ndarray:
    """ZOH-discretized free-run response from zero state; same timing as the plant runs."""
    if delay:
        u = np.concatenate([np.zeros(delay), u[:-delay]])
    Ad, Bd, *_ = cont2discrete((A, B, C, np.zeros((1, 1))), 1 / CONTROL_HZ)
    x = np.zeros(A.shape[0])
    y = np.empty(u.size)
    for k, uk in enumerate(u):
        x = Ad @ x + Bd[:, 0] * uk
        y[k] = C[0] @ x
    return y


def validation_input(seed: int = VAL_SEED, duration_s: float = 120.0) -> np.ndarray:
    """Random steps on each channel: levels uniform in +/-2 psi, held 0.5-4 s.
    A different kind of signal from the multisine, with its own seed."""
    rng = np.random.default_rng(seed)
    n = int(duration_s * CONTROL_HZ)
    u = np.zeros((n, 2))
    for j in range(2):
        k = 0
        while k < n:
            hold = int(rng.uniform(0.5, 4.0) * CONTROL_HZ)
            u[k:k + hold, j] = rng.uniform(-2.0, 2.0)
            k += hold
    return u


