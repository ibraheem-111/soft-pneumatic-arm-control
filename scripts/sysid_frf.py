EXCITATIONS = {
    # v1: every odd harmonic of 0.02 Hz up to 2.98 Hz (evenly spaced lines)
    "v1": {"f0": 0.02, "k_max": 149, "log_ratio": None, "periods": 6, "transient": 2},
    # v2: 0.01 Hz resolution; odd harmonics thinned to a quasi-logarithmic grid
    # (each kept line at least 6 % above the previous one) up to 2.99 Hz
    "v2": {"f0": 0.01, "k_max": 299, "log_ratio": 1.06, "periods": 6, "transient": 1},
}
PHASE_SEED = 21
AMPLITUDES = (2.0, 1.0)     # peak psi per channel
LAG_CORNER_HZ = 0.27        # for plot annotations only; the fits below do not use tau


def n_period(spec: dict) -> int:
    return int(round(CONTROL_HZ / spec["f0"]))


def cache_path(version: str) -> Path:
    return CACHE_DIR / f"sysid_frf_{version}.npz"


def candidate_lines(spec: dict) -> np.ndarray:
    """Odd harmonics eligible for excitation (all of them, or a quasi-log subset)."""
    odd = np.arange(1, spec["k_max"] + 1, 2)
    if spec["log_ratio"] is None:
        return odd
    lines = [odd[0]]
    for k in odd[1:]:
        if k >= lines[-1] * spec["log_ratio"]:
            lines.append(k)
    return np.array(lines)


def design_multisine(spec: dict, peak: float = AMPLITUDES[0], seed: int = PHASE_SEED,
                     tries: int = 500) -> dict:
    """Random-phase odd multisine over one period, flat amplitude on the excited lines.

    The candidate odd lines are split into groups of four; one line per group is left
    out at random and becomes an odd detection line. Of `tries` random phase sets the
    one with the lowest crest factor (peak / rms) is kept."""
    rng = np.random.default_rng(seed)
    cand = candidate_lines(spec)
    excited, detect_odd = [], []
    for g in range(0, cand.size, 4):
        group = cand[g:g + 4]
        drop = rng.integers(group.size) if group.size == 4 else -1
        for i, k in enumerate(group):
            (detect_odd if i == drop else excited).append(k)
    excited = np.array(excited)
    N = n_period(spec)
    best_cf, best = np.inf, None
    for _ in range(tries):
        spectrum = np.zeros(N // 2 + 1, complex)
        spectrum[excited] = np.exp(1j * rng.uniform(0, 2 * np.pi, excited.size))
        x = np.fft.irfft(spectrum, N)
        cf = np.abs(x).max() / x.std()
        if cf < best_cf:
            best_cf, best = cf, x
    return {"signal": best * peak / np.abs(best).max(), "excited": excited,
            "detect_odd": np.array(detect_odd), "crest": best_cf, "peak": peak}


def design_report(version: str) -> None:
    """Step 2: describe and plot the excitation."""
    spec = EXCITATIONS[version]
    N, f0 = n_period(spec), spec["f0"]
    d = design_multisine(spec)
    m, exc, det = d["signal"], d["excited"], d["detect_odd"]
    per_line = 2 * np.abs(np.fft.rfft(m)[exc]).mean() / N
    command = BIAS_PSI + channel_matrix() @ np.vstack([m, m])   # experiment "+"
    print(f"Step 2 - excitation design {version}")
    print(f"  period {N / CONTROL_HZ:.0f} s ({N} samples), resolution {f0} Hz")
    print(f"  excited lines: {exc.size} odd harmonics, {exc[0] * f0:.2f}-{exc[-1] * f0:.2f} Hz; "
          f"{np.sum(exc * f0 < LAG_CORNER_HZ)} below the 0.27 Hz lag corner, "
          f"{np.sum(exc * f0 > 1.0)} above 1 Hz")
    print(f"  detection lines: {det.size} odd (left out) + all even harmonics")
    print(f"  crest factor {d['crest']:.2f}; rms {m.std():.3f} psi at peak {d['peak']} psi; "
          f"amplitude per excited line {per_line:.4f} psi")
    print(f"  pouch commands over a period: {command.min():.2f}-{command.max():.2f} psi (limit 0-9)")

    t = np.arange(N) / CONTROL_HZ
    fig, ax = plt.subplots(1, 2, figsize=(12, 4))
    ax[0].plot(t, m, lw=0.7)
    for s in (1, -1):
        ax[0].axhline(s * d["peak"], color="k", ls=":", lw=1)
    ax[0].set(xlabel="time [s]", ylabel="channel command deviation [psi]",
              title=f"{version}: one period of the multisine (crest factor {d['crest']:.2f})")
    amp = 2 * np.abs(np.fft.rfft(m)) / N
    f = np.arange(amp.size) * f0
    ax[1].vlines(f[exc], 0, amp[exc], color="C0", lw=1.5, label=f"excited odd lines ({exc.size})")
    ax[1].plot(f[det], np.full(det.size, amp[exc].max() * 0.15), "x", color="C3",
               label=f"odd detection lines ({det.size})")
    ax[1].axvline(LAG_CORNER_HZ, color="k", ls="--", lw=1, label="lag corner 0.27 Hz")
    ax[1].axvline(1.142, color="k", ls=":", lw=1, label="mechanical pair 1.14 Hz")
    ax[1].axvspan(1.25 / (2 * np.pi), 1.81 / (2 * np.pi), color="0.85", label="slow real poles")
    ax[1].set(xscale="log", xlim=(0.007, 4), xlabel="frequency [Hz]", ylabel="amplitude [psi]",
              title=f"{version}: amplitude spectrum")
    for a in ax:
        a.grid(True, alpha=0.3)
    ax[1].legend(fontsize=8, loc="lower left")
    fig.tight_layout()
    out = FIG_DIR / f"sysid_excitation_{version}.png"
    fig.savefig(out, dpi=130)
    print(f"  figure: {out.relative_to(FIG_DIR.parent.parent)}")


def run_experiments(version: str) -> dict:
    """Step 3: Hadamard pair of experiments at each amplitude; cache raw signals."""
    spec = EXCITATIONS[version]
    base = design_multisine(spec)
    data = {"excited": base["excited"], "detect_odd": base["detect_odd"]}
    i = 0
    for peak in AMPLITUDES:
        m = base["signal"] * peak / base["peak"]
        for sign, label in ((1.0, "+"), (-1.0, "-")):
            u = np.tile(np.column_stack([m, sign * m]), (spec["periods"], 1))
            plant = ChannelPlant(sim_seed=SIM_SEED + i, noise_seed=NOISE_SEED + i)
            for k, v in plant.run(u).items():
                data[f"{peak:g}{label}/{k}"] = v
            i += 1
    CACHE_DIR.mkdir(exist_ok=True)
    np.savez_compressed(cache_path(version), **data)
    return data


def load_runs(version: str) -> dict:
    path = cache_path(version)
    if not path.exists():
        return run_experiments(version)
    with np.load(path) as z:
        return {k: z[k] for k in z.files}


def periods_dft(x: np.ndarray, spec: dict) -> np.ndarray:
    """(periods * N, c) -> (periods, N // 2 + 1, c): DFT of each period separately."""
    N = n_period(spec)
    return np.fft.rfft(x.reshape(spec["periods"], N, -1), axis=1)


def run_report(version: str) -> None:
    """Step 3: run, then check steady state, SNR and the raw output spectra."""
    spec = EXCITATIONS[version]
    N, f0, P, Pt = n_period(spec), spec["f0"], spec["periods"], spec["transient"]
    data = run_experiments(version)
    exc, det_odd = data["excited"], data["detect_odd"]
    even = np.arange(2, spec["k_max"] + 1, 2)
    print(f"Step 3 - experiments {version}")
    print(f"  {len(AMPLITUDES) * 2} experiments x {P} periods = "
          f"{len(AMPLITUDES) * 2 * P * N / CONTROL_HZ:.0f} s simulated; cached in .cache/{cache_path(version).name}")
    changes = {}
    for exp in ("2+", "2-", "1+", "1-"):
        for sig, name in (("p_meas", "px"), ("tip_meas", "tip x"), ("tip_true", "tip x true")):
            Y = periods_dft(data[f"{exp}/{sig}"], spec)[:, exc, 0]
            changes[(exp, name)] = np.linalg.norm(Y - Y[-1], axis=1) / np.linalg.norm(Y[-1])
            if exp == "2+":
                print(f"    steady state {exp} {name:<11}" + "  ".join(
                    f"P{p + 1} {c:.1e}" for p, c in enumerate(changes[(exp, name)][:-1])))
    print(f"  averaging periods {Pt + 1}-{P} ({P - Pt} periods)")
    spectra = {}
    for exp in ("2+", "1+"):
        for sig, name in (("p_meas", "px"), ("tip_meas", "tip x"), ("tip_true", "tip x true")):
            Y = periods_dft(data[f"{exp}/{sig}"], spec)[Pt:, :, 0]
            Ym = np.abs(Y.mean(0))
            se = np.abs(Y - Y.mean(0)).std(0) * np.sqrt(2) / np.sqrt(Y.shape[0])
            spectra[(exp, name)] = Ym
            e = np.median(Ym[exc])
            snr = 20 * np.log10(np.median(Ym[exc] / np.maximum(se[exc], 1e-30)))
            low = exc * f0 < LAG_CORNER_HZ
            snr_low = 20 * np.log10(np.median(Ym[exc][low] / np.maximum(se[exc][low], 1e-30)))
            print(f"    {exp} {name:<11} odd-detection {20 * np.log10(np.median(Ym[det_odd]) / e):+6.1f} dB  "
                  f"even-detection {20 * np.log10(np.median(Ym[even]) / e):+6.1f} dB  "
                  f"median SNR {snr:5.1f} dB (below 0.27 Hz: {snr_low:5.1f} dB)")

    exp = "2+"
    t = np.arange(P * N) / CONTROL_HZ
    fig, ax = plt.subplots(3, 1, figsize=(12, 11))
    ax[0].axvspan(0, Pt * N / CONTROL_HZ, color="0.92", label="discarded periods")
    ax[0].plot(t, data[f"{exp}/u"][:, 0], lw=0.4, color="0.55", label="command ux")
    ax[0].plot(t, data[f"{exp}/p_meas"][:, 0], lw=0.5, label="measured px")
    ax0b = ax[0].twinx()
    ax0b.plot(t, 1000 * data[f"{exp}/tip_meas"][:, 0], lw=0.4, color="C3")
    ax0b.set_ylabel("measured tip x [mm]", color="C3")
    ax[0].set(xlabel="time [s]", ylabel="psi", title=f"{version}, experiment 2+ (peak 2 psi), {P} periods")
    ax[0].legend(fontsize=8, loc="upper left")
    for (e, name), c in changes.items():
        if name != "tip x true":
            ax[1].semilogy(np.arange(1, P), c[:-1], "o-", ms=4, label=f"{e} {name}")
    ax[1].axvline(Pt + 0.5, color="k", ls=":", lw=1)
    ax[1].set(xlabel="period", ylabel=f"relative change vs period {P}",
              title="Steady state: how much each period's spectrum differs from the last")
    ax[1].legend(fontsize=7, ncol=4)
    f = np.arange(N // 2 + 1) * f0
    scale = 1000 * 2 / N
    Ym, Yt = spectra[(exp, "tip x")], spectra[(exp, "tip x true")]
    ax[2].loglog(f[exc], scale * Ym[exc], "o", ms=3, label="excited lines")
    ax[2].loglog(f[det_odd], scale * Ym[det_odd], "x", ms=5, label="odd detection lines")
    ax[2].loglog(f[even], scale * Ym[even], ".", ms=2, color="0.6", label="even detection lines")
    ax[2].loglog(f[det_odd], scale * Yt[det_odd], "+", ms=6, color="C3", label="odd detection, noise-free tip")
    ax[2].set(xlim=(0.007, 4), xlabel="frequency [Hz]", ylabel="amplitude [mm]",
              title=f"Raw spectrum of measured tip x, {version} experiment 2+, mean of kept periods")
    for a in ax:
        a.grid(True, alpha=0.3, which="both")
